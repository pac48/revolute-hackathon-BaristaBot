"""Collision geometry of an MJCF, per body: parsing, STL loading and geom placement.

Shared by seed_spheres (spherization) and export_spheres_obj (visualization).
Body frames are the URDF link frames of URDFs generated by mjcf_to_urdf.
"""

import math
import os
import struct
import xml.etree.ElementTree as ET

import numpy as np


def quat_matrix(wxyz) -> np.ndarray:
    w, x, y, z = np.asarray(wxyz, float) / np.linalg.norm(wxyz)
    return np.array(
        [
            [1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)],
            [2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)],
            [2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)],
        ]
    )


def vec(element, attr, default) -> np.ndarray:
    return np.array([float(v) for v in element.get(attr, default).split()])


def read_stl_triangles(path: str) -> np.ndarray:
    """Triangles of a binary STL, shape (n, 3, 3)."""
    data = open(path, "rb").read()
    (n,) = struct.unpack_from("<I", data, 80)
    if 84 + 50 * n != len(data):
        raise ValueError(f"{path}: not a binary STL")
    records = np.frombuffer(data, dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]),
                            count=n, offset=84)
    return records["v"].astype(float)


def is_collision(geom) -> bool:
    return geom.get("contype", "1") != "0" or geom.get("conaffinity", "1") != "0"


def _meshdir(root, file_dir: str, default: str) -> str:
    """The meshdir of a model: its <compiler>'s, which may be in a file it includes."""
    compiler = root.find("compiler")
    if compiler is not None and compiler.get("meshdir") is not None:
        return compiler.get("meshdir")
    for include in root.iter("include"):
        path = os.path.join(file_dir, include.get("file"))
        found = _meshdir(ET.parse(path).getroot(), os.path.dirname(path), None)
        if found is not None:
            return found
    return default


def collision_geoms(mjcf_path: str):
    """({body: [geom element, ...]}, {mesh name: (STL path, scale)}) for collision geoms.

    <include> and <attach> are followed (a body of an attached model is named prefix + its name, as in the
    composed model; the attach's `body` selection is not applied: all the model's bodies count). Paths
    are not resolved through symlinks, so an MJCF in a symlink tree finds its meshes next to it."""
    bodies, meshes, models = {}, {}, {}

    def visit(elem, model_dir, meshdir, prefix, file_dir, body):
        for c in elem:
            if c.tag == "include":
                path = os.path.join(file_dir, c.get("file"))
                visit(ET.parse(path).getroot(), model_dir, meshdir, prefix, os.path.dirname(path), body)
            elif c.tag == "model" and c.get("file"):
                models[c.get("name")] = os.path.abspath(os.path.join(file_dir, c.get("file")))
            elif c.tag == "attach":
                path = models[c.get("model")]
                root = ET.parse(path).getroot()
                own = _meshdir(root, os.path.dirname(path), meshdir)
                visit(root, os.path.dirname(path), own, prefix + c.get("prefix", ""), os.path.dirname(path), None)
            elif c.tag == "mesh":
                if c.get("file"):
                    name = c.get("name") or os.path.splitext(os.path.basename(c.get("file")))[0]
                    meshes[prefix + name] = (os.path.join(model_dir, meshdir, c.get("file")), vec(c, "scale", "1 1 1"))
            elif c.tag == "geom":
                if body is not None and is_collision(c):
                    g = ET.Element("geom", dict(c.attrib))
                    if g.get("mesh"):
                        g.set("mesh", prefix + g.get("mesh"))
                    bodies[body].append(g)
            elif c.tag == "body":
                name = prefix + c.get("name")
                bodies.setdefault(name, [])
                visit(c, model_dir, meshdir, prefix, file_dir, name)
            else:
                visit(c, model_dir, meshdir, prefix, file_dir, body)

    path = os.path.abspath(mjcf_path)
    root = ET.parse(path).getroot()
    visit(root, os.path.dirname(path), _meshdir(root, os.path.dirname(path), ""), "", os.path.dirname(path), None)
    return {body: geoms for body, geoms in bodies.items() if geoms}, meshes


def geom_kind(geom) -> str:
    return geom.get("type", "mesh" if geom.get("mesh") else "sphere")


def geom_transform(geom) -> np.ndarray:
    """4x4 pose of the geom in its body frame (pos + quat)."""
    if geom.get("fromto"):
        raise ValueError(f"geom {geom.get('name')}: fromto is not supported; use pos/quat")
    for attr in ("euler", "axisangle", "xyaxes", "zaxis"):
        if geom.get(attr):
            raise ValueError(f"geom {geom.get('name')}: orientation via {attr} is not supported; use quat")
    t = np.eye(4)
    t[:3, :3] = quat_matrix(vec(geom, "quat", "1 0 0 0"))
    t[:3, 3] = vec(geom, "pos", "0 0 0")
    return t


def mesh_triangles(geom, meshes) -> np.ndarray:
    """Triangles (n, 3, 3) of a mesh geom, in its body frame."""
    path, scale = meshes[geom.get("mesh")]
    t = geom_transform(geom)
    return (read_stl_triangles(path) * scale) @ t[:3, :3].T + t[:3, 3]


def primitive_points(geom) -> np.ndarray:
    """Points on the surface of a primitive geom, in its body frame."""
    kind = geom_kind(geom)
    size = vec(geom, "size", "0 0 0")
    if kind == "sphere":
        points = _ball(size[0])
    elif kind == "capsule":
        points = np.vstack([_ball(size[0]) + [0, 0, s * size[1]] for s in (-1, 1)])
    elif kind == "cylinder":
        points = np.vstack([_ring(size[0]) + [0, 0, s * size[1]] for s in (-1, 1)])
    elif kind == "box":
        points = np.array([[sx, sy, sz] for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]) * size[:3]
    else:
        raise ValueError(f"geom type {kind} is not supported")
    t = geom_transform(geom)
    return points @ t[:3, :3].T + t[:3, 3]


def _ring(r, n=16):
    a = np.linspace(0, 2 * math.pi, n, endpoint=False)
    return np.stack([r * np.cos(a), r * np.sin(a), np.zeros(n)], axis=1)


def _ball(r):
    return np.vstack([_ring(r) @ quat_matrix([1, 0, 0, 0]).T, _ring(r) @ quat_matrix([0.7071, 0.7071, 0, 0]).T,
                      np.array([[0, 0, r], [0, 0, -r]])])
