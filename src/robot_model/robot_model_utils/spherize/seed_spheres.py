"""Seed a sphere spec (spheres_spec.py) from an MJCF's collision geometry.

    seed_spheres --mjcf robot.xml --out spheres.yaml [--fix JOINT=POS ...]
        [--method foam|kmeans|chain] [--spheres N] [--max-triangles N]
        [--base-spec spheres.yaml] [--save-meshes DIR]

For each body, its collision geoms (contype/conaffinity not 0) are placed in
the body frame (= the URDF link frame for URDFs generated by mjcf_to_urdf) and
approximated by spheres:
  foam (default)  foam's medial-axis spherization (//third_party/foam), up to
                  --spheres spheres per collision geom. Meshes are first
                  decimated to --max-triangles (foam's quadric simplifier):
                  SphereTree samples >= 5 points per triangle, so raw CAD
                  meshes (100k+ triangles) take minutes each.
  kmeans          --spheres clusters of mesh vertices per body, each sphere
                  covering its cluster's vertices; bulges on flat surfaces.
  chain           spheres along the body's principal axis; coarse.
--base-spec keeps fixed_joints and disable_collisions from an existing spec.
--save-meshes writes the meshes given to foam (after decimation) as OBJ.
Meshes are read from binary STL.
"""

import argparse
import math
import os
import sys
import time

import numpy as np

from src.robot_model.robot_model_utils.spherize import mjcf_collision as mc
from src.robot_model.robot_model_utils.spherize import spheres_spec


def body_points(mjcf_path: str) -> dict[str, np.ndarray]:
    """Points covering each body's collision geoms (mesh vertices), in the body frame."""
    bodies, meshes = mc.collision_geoms(mjcf_path)
    out = {}
    for body, geoms in bodies.items():
        parts = []
        for g in geoms:
            if mc.geom_kind(g) == "mesh":
                parts.append(np.unique(mc.mesh_triangles(g, meshes).reshape(-1, 3), axis=0))
            else:
                parts.append(mc.primitive_points(g))
        out[body] = np.vstack(parts)
    return out


# ---------------------------------------------------------------------------
# foam

FOAM_TOOLS = ("makeTreeMedial", "makeTreeGrid", "makeTreeHubbard", "makeTreeOctree", "makeTreeSpawn",
              "manifold", "simplify", "manifold_old", "simplify_old")


def import_foam():
    """foam, with its tools resolved from runfiles (FOAM_RLOCATION_<tool>, set by the
    BUILD target) into FOAM_BINARY_<tool>, which foam reads when imported."""
    from python.runfiles import Runfiles

    runfiles = Runfiles.Create()
    for tool in FOAM_TOOLS:
        rlocation = os.environ.get(f"FOAM_RLOCATION_{tool}")
        if rlocation and f"FOAM_BINARY_{tool}" not in os.environ:
            os.environ[f"FOAM_BINARY_{tool}"] = runfiles.Rlocation(rlocation)
    import foam

    return foam


def geom_mesh(geom, meshes):
    """The geom as a trimesh.Trimesh in its body's frame."""
    import trimesh

    kind = mc.geom_kind(geom)
    size = mc.vec(geom, "size", "0 0 0")
    if kind == "mesh":
        triangles = mc.mesh_triangles(geom, meshes)
        mesh = trimesh.Trimesh(vertices=triangles.reshape(-1, 3), faces=np.arange(len(triangles) * 3).reshape(-1, 3))
        mesh.merge_vertices()
        return mesh
    if kind == "sphere":
        mesh = trimesh.creation.icosphere(radius=size[0])
    elif kind == "capsule":
        mesh = trimesh.creation.capsule(height=2 * size[1], radius=size[0])
    elif kind == "cylinder":
        mesh = trimesh.creation.cylinder(radius=size[0], height=2 * size[1])
    elif kind == "box":
        mesh = trimesh.creation.box(extents=2 * size[:3])
    else:
        raise ValueError(f"geom type {kind} is not supported")
    mesh.apply_transform(mc.geom_transform(geom))
    return mesh


def cover_foam(foam, name: str, geoms, meshes, spheres_per_geom: int, max_triangles: int, save_dir: str | None):
    """foam medial-axis spheres for every collision geom of a body, in the body frame."""
    out = []
    for i, geom in enumerate(geoms):
        label = f"{name}[{i}]"
        mesh = geom_mesh(geom, meshes)
        original = len(mesh.faces)
        if max_triangles and original > max_triangles:
            mesh = foam.simplify(mesh, ratio=max_triangles / original)
        if save_dir:
            mesh.export(os.path.join(save_dir, f"{name}_{i}.obj"))
        t0 = time.monotonic()
        levels = foam.spherize_mesh(
            label,
            mesh,
            spherization_kwargs={"depth": 1, "branch": spheres_per_geom, "method": "medial"},
            process_kwargs={"manifold_leaves": 1000, "ratio": 0.2},
        )
        spheres = [(float(s.origin[0]), float(s.origin[1]), float(s.origin[2]), float(s.radius))
                   for s in levels[-1].spheres]
        print(f"seed_spheres: {label}: {original} -> {len(mesh.faces)} triangles, {len(spheres)} spheres "
              f"in {time.monotonic() - t0:.1f} s", file=sys.stderr, flush=True)
        out += spheres
    return out


# ---------------------------------------------------------------------------
# kmeans / chain


def cover(points: np.ndarray, max_spheres: int) -> list[tuple[float, float, float, float]]:
    """A chain of spheres along the principal axis covering every point."""
    center = points.mean(axis=0)
    _, _, vt = np.linalg.svd(points - center, full_matrices=False)
    axis = vt[0]
    t = (points - center) @ axis
    radial = np.linalg.norm((points - center) - np.outer(t, axis), axis=1)
    thickness = max(radial.max(), 1e-3)
    n = int(min(max_spheres, max(1, math.ceil((t.max() - t.min()) / thickness))))
    edges = np.linspace(t.min(), t.max(), n + 1)
    spheres = []
    for i in range(n):
        last = i == n - 1
        seg = points[(t >= edges[i]) & ((t <= edges[i + 1]) if last else (t < edges[i + 1]))]
        if len(seg) == 0:
            continue
        c = seg.mean(axis=0)
        r = float(np.linalg.norm(seg - c, axis=1).max())
        spheres.append((float(c[0]), float(c[1]), float(c[2]), max(r, 1e-3)))
    return spheres


def cover_kmeans(points: np.ndarray, k: int, iterations: int = 25, sample: int = 6000):
    """k spheres around k-means clusters of the points; every point is covered."""
    k = min(k, len(points))
    step = max(1, len(points) // sample)
    fit = points[::step]
    # Farthest-point initialization: deterministic and spread over the shape.
    centers = [fit[np.argmax(np.linalg.norm(fit - fit.mean(axis=0), axis=1))]]
    dist = np.linalg.norm(fit - centers[0], axis=1)
    for _ in range(k - 1):
        centers.append(fit[np.argmax(dist)])
        dist = np.minimum(dist, np.linalg.norm(fit - centers[-1], axis=1))
    centers = np.array(centers)
    for _ in range(iterations):
        labels = np.argmin(np.linalg.norm(fit[:, None] - centers[None], axis=2), axis=1)
        moved = np.array([fit[labels == i].mean(axis=0) if np.any(labels == i) else centers[i] for i in range(k)])
        if np.allclose(moved, centers):
            break
        centers = moved
    labels = np.argmin(np.linalg.norm(points[:, None] - centers[None], axis=2), axis=1)
    spheres = []
    for i in range(k):
        members = points[labels == i]
        if len(members):
            r = float(np.linalg.norm(members - centers[i], axis=1).max())
            spheres.append((float(centers[i][0]), float(centers[i][1]), float(centers[i][2]), max(r, 1e-3)))
    return spheres


def workspace_path(path: str) -> str:
    """Relative paths are from the workspace under bazel run."""
    if not os.path.isabs(path) and "BUILD_WORKSPACE_DIRECTORY" in os.environ:
        return os.path.join(os.environ["BUILD_WORKSPACE_DIRECTORY"], path)
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mjcf", required=True)
    ap.add_argument("--out", required=True, help="spec YAML; relative paths are from the workspace under bazel run")
    ap.add_argument("--fix", nargs="*", default=[], metavar="JOINT=POS", help="fixed_joints for the spec")
    ap.add_argument("--method", choices=["foam", "kmeans", "chain"], default="foam")
    ap.add_argument("--spheres", type=int, default=8,
                    help="foam: maximum per collision geom; kmeans: per link; chain: maximum per link (default 8)")
    ap.add_argument("--max-triangles", type=int, default=2000,
                    help="foam: decimate meshes to at most this many triangles first (0: don't; default 2000)")
    ap.add_argument("--base-spec", help="keep fixed_joints and disable_collisions from this spec")
    ap.add_argument("--save-meshes", metavar="DIR", help="foam: write the meshes given to foam as OBJ here")
    args = ap.parse_args()

    if args.method == "foam":
        foam = import_foam()
        save_dir = workspace_path(args.save_meshes) if args.save_meshes else None
        if save_dir:
            os.makedirs(save_dir, exist_ok=True)
        bodies, meshes = mc.collision_geoms(args.mjcf)
        spheres = {
            body: cover_foam(foam, body, geoms, meshes, args.spheres, args.max_triangles, save_dir)
            for body, geoms in bodies.items()
        }
    else:
        cover_fn = cover_kmeans if args.method == "kmeans" else cover
        spheres = {body: cover_fn(p, args.spheres) for body, p in body_points(args.mjcf).items()}
    base = spheres_spec.load_spec(workspace_path(args.base_spec)) if args.base_spec else None
    spec = spheres_spec.Spec(
        spheres=spheres,
        fixed_joints=dict(base.fixed_joints) if base else {},
        disable_collisions=list(base.disable_collisions) if base else [],
    )
    spec.fixed_joints.update({j: float(v) for j, _, v in (f.partition("=") for f in args.fix)})
    out = workspace_path(args.out)
    method = f"{args.method}, --spheres {args.spheres}"
    if args.method == "foam":
        method += f", --max-triangles {args.max_triangles}"
    header = (
        f"Collision spheres for VAMP, seeded by seed_spheres from {os.path.basename(args.mjcf)}\n"
        f"({method}). Tune by hand; see spheres_spec.py."
    )
    with open(out, "w") as f:
        f.write(spheres_spec.dump_spec(spec, header))
    total = sum(len(s) for s in spec.spheres.values())
    print(f"seed_spheres: {total} spheres on {len(spec.spheres)} links -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
