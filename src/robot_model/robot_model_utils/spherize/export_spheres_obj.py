"""Export a sphere spec's spheres (and optionally the MJCF collision meshes) as OBJ.

    export_spheres_obj --urdf robot.urdf --spec spheres.yaml [more.yaml ...] --out robot_spheres.obj
        [--mjcf robot.xml] [--config JOINT=POS ...] [--subdivisions 2] [--prefix left_ right_]

Several specs are merged (the parts of one robot). With --prefix the specs are those of one arm, put on
the URDF once per prefix (as prefix_spec does for the dual-arm model).

The links are laid out apart from each other in rows (--assembled: where the robot has them, at the
given configuration: joints not listed at 0, the spec's fixed_joints at their positions), so one link's
spheres are easy to edit without touching another's. Each link keeps its orientation; the OBJ's header
records where its frame is and the ball around its geometry (import_spheres_obj assigns spheres to links
by which ball they are in). Opens directly in Blender (File > Import > Wavefront OBJ; Z up, Y forward). One OBJ
object per sphere, sphere_<link>_<index> (an icosphere), and, with --mjcf,
mesh_<link> (that link's collision meshes), to check how well the spheres
cover the geometry. Edit the spheres in Blender (move, scale, duplicate,
delete; keep the sphere_<link>_ prefix, see import_spheres_obj.py) and bring
them back with import_spheres_obj. --urdf is the URDF the spec is for (e.g. one generated by
mjcf_to_urdf, whose link frames are the MJCF body frames).
"""

import argparse
import os
import sys
import xml.etree.ElementTree as ET

import numpy as np

from src.robot_model.robot_model_utils.spherize import mjcf_collision as mc
from src.robot_model.robot_model_utils.spherize import prefix_spec
from src.robot_model.robot_model_utils.spherize import spheres_spec


def icosphere(subdivisions: int):
    """Unit icosphere: (vertices, faces)."""
    t = (1 + 5**0.5) / 2
    verts = [[-1, t, 0], [1, t, 0], [-1, -t, 0], [1, -t, 0], [0, -1, t], [0, 1, t], [0, -1, -t], [0, 1, -t],
             [t, 0, -1], [t, 0, 1], [-t, 0, -1], [-t, 0, 1]]
    faces = [[0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11], [1, 5, 9], [5, 11, 4], [11, 10, 2],
             [10, 7, 6], [7, 1, 8], [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9], [4, 9, 5], [2, 4, 11],
             [6, 2, 10], [8, 6, 7], [9, 8, 1]]
    verts = [np.array(v, float) / np.linalg.norm(v) for v in verts]
    for _ in range(subdivisions):
        midpoints = {}

        def midpoint(a, b):
            key = (min(a, b), max(a, b))
            if key not in midpoints:
                m = verts[a] + verts[b]
                verts.append(m / np.linalg.norm(m))
                midpoints[key] = len(verts) - 1
            return midpoints[key]

        new_faces = []
        for a, b, c in faces:
            ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
            new_faces += [[a, ab, ca], [b, bc, ab], [c, ca, bc], [ab, bc, ca]]
        faces = new_faces
    return np.array(verts), np.array(faces)


class ObjWriter:
    def __init__(self, f):
        self.f = f
        self.offset = 1  # OBJ indices are 1-based and global

    def add(self, name: str, vertices: np.ndarray, faces: np.ndarray):
        self.f.write(f"o {name}\n")
        self.f.writelines(f"v {x:.6f} {y:.6f} {z:.6f}\n" for x, y, z in vertices)
        self.f.writelines(f"f {a + self.offset} {b + self.offset} {c + self.offset}\n" for a, b, c in faces)
        self.offset += len(vertices)


def transform(points: np.ndarray, pose: np.ndarray) -> np.ndarray:
    return points @ pose[:3, :3].T + pose[:3, 3]


def expanded_spec(paths: list[str], prefixes: list[str]) -> spheres_spec.Spec:
    """The specs merged, once per prefix (the one spec of the robot as the URDF has it)."""
    one = spheres_spec.merge_specs([spheres_spec.load_spec(p) for p in paths])
    return spheres_spec.merge_specs([prefix_spec.prefixed(one, p) for p in prefixes])


def link_meshes(mjcf: str, links) -> dict[str, np.ndarray]:
    """Each link's collision mesh triangles' vertices (n*3, 3) in the link frame (the OBJ's vertex order)."""
    bodies, meshes = mc.collision_geoms(mjcf)
    out = {}
    for body, geoms in bodies.items():
        if body not in links:
            print(f"export_spheres_obj: body {body} is not a URDF link; skipped", file=sys.stderr)
            continue
        tris = [mc.mesh_triangles(g, meshes) for g in geoms if mc.geom_kind(g) == "mesh"]
        if tris:
            out[body] = np.vstack(tris).reshape(-1, 3)
    return out


def bounding_balls(geometry: dict[str, np.ndarray]) -> dict[str, tuple[np.ndarray, float]]:
    """Each link's (center, radius) of a ball around its geometry, in the link frame."""
    balls = {}
    for link, pts in geometry.items():
        center = (pts.min(axis=0) + pts.max(axis=0)) / 2
        balls[link] = (center, float(np.linalg.norm(pts - center, axis=1).max()))
    return balls


def exploded_poses(poses: dict[str, np.ndarray], geometry: dict[str, np.ndarray], gap: float = 0.03):
    """Poses that keep each link's orientation but lay the links out in rows, apart from each other: every
    link's geometry (points in its frame) lies in a ball, and the balls are placed side by side, so no
    two links' geometry can touch, whatever is edited within a ball's size. Links without geometry stay."""
    out = dict(poses)
    balls = bounding_balls(geometry)
    x = y = row_height = 0.0
    row_width = max(1.0, 2.5 * np.sqrt(sum((2 * r + gap) ** 2 for _, r in balls.values())))
    for link, (center, r) in balls.items():
        d = 2 * r + gap
        if x > 0 and x + d > row_width:
            x, y, row_height = 0.0, y - row_height, 0.0
        target = np.array([x + d / 2, y - d / 2, 0.0])
        pose = poses[link].copy()
        pose[:3, 3] = target - pose[:3, :3] @ center
        out[link] = pose
        x += d
        row_height = max(row_height, d)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--urdf", required=True, help="URDF the spec's link frames refer to")
    ap.add_argument("--spec", nargs="+", required=True)
    ap.add_argument("--prefix", nargs="*", default=[""], help="name prefixes of the copies of the spec's robot")
    ap.add_argument("--out", required=True, help="OBJ file; relative paths are from the workspace under bazel run")
    ap.add_argument("--mjcf", help="also export the MJCF's collision meshes (body names = link names)")
    ap.add_argument("--config", nargs="*", default=[], metavar="JOINT=POS", help="joint positions (default 0)")
    ap.add_argument("--subdivisions", type=int, default=2, help="icosphere detail (2: 320 faces per sphere)")
    ap.add_argument("--assembled", action="store_true",
                    help="keep the links where the robot has them instead of laying them apart in rows")
    args = ap.parse_args()

    def workspace(path):
        if not os.path.isabs(path) and "BUILD_WORKSPACE_DIRECTORY" in os.environ:
            return os.path.join(os.environ["BUILD_WORKSPACE_DIRECTORY"], path)
        return path

    spec = expanded_spec([workspace(p) for p in args.spec], args.prefix)
    robot = ET.parse(args.urdf).getroot()
    spheres_spec.freeze_joints(robot, spec.fixed_joints)
    q = {j: float(v) for j, _, v in (c.partition("=") for c in args.config)}
    poses = spheres_spec.link_poses(robot, q)
    unit_verts, unit_faces = icosphere(args.subdivisions)

    meshes = link_meshes(args.mjcf, poses) if args.mjcf else {}
    geometry = {}
    for link in poses:
        pts = [meshes[link]] if link in meshes else []
        for x, y, z, r in spec.spheres.get(link, []):  # the spheres' extreme points
            pts.append(np.array([x, y, z]) + r * np.vstack([np.eye(3), -np.eye(3)]))
        if pts:
            geometry[link] = np.vstack(pts)
    if not args.assembled:
        poses = exploded_poses(poses, geometry)

    out = workspace(args.out)
    n_spheres = 0
    with open(out, "w") as f:
        f.write(f"# spheres from {', '.join(os.path.basename(p) for p in args.spec)} at {q or 'all joints 0'}\n")
        f.write("# config: " + " ".join(f"{j}={v:g}" for j, v in q.items()) + "\n")
        # where each link's frame is in this file (import_spheres_obj puts the spheres back relative to it)
        for link, (center, radius) in bounding_balls(geometry).items():
            f.write(f"# link_pose {link} " + " ".join(f"{v:.9g}" for v in poses[link].reshape(-1)) + "\n")
            f.write(f"# link_ball {link} " + " ".join(f"{v:.9g}" for v in [*center, radius]) + "\n")
        writer = ObjWriter(f)
        for link, spheres in spec.spheres.items():
            for i, (x, y, z, r) in enumerate(spheres):
                writer.add(f"sphere_{link}_{i}", transform(unit_verts * r + [x, y, z], poses[link]), unit_faces)
            n_spheres += len(spheres)
        for link, verts in meshes.items():
            writer.add(f"mesh_{link}", transform(verts, poses[link]), np.arange(len(verts)).reshape(-1, 3))
    print(f"export_spheres_obj: {n_spheres} spheres" + (f", {len(meshes)} link meshes" if args.mjcf else "")
          + f" -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
